    /** 1.19.2 GameTestHelper has no assertTrue; GameTestAssertException(String) is public [V]. */
    public static void check(boolean condition, Supplier<String> message) {
        if (!condition) {
            throw new GameTestAssertException(message.get());
        }
    }

    public static void checkAt(GameTestHelper helper, boolean condition, BlockPos rel, Supplier<String> message) {
        if (!condition) {
            throw new GameTestAssertPosException(message.get(), helper.absolutePos(rel), rel, helper.getTick());
        }
    }

    public static <T extends BlockEntity> T tile(GameTestHelper helper, BlockPos rel, Class<T> type) {
        BlockEntity be = helper.getBlockEntity(rel);
        checkAt(helper, type.isInstance(be), rel, () -> "expected " + type.getSimpleName() + " but found " + be);
        return type.cast(be);
    }

    public static String head(Collection<String> items) {
        return items.stream().limit(25).collect(Collectors.joining(", ")) + (items.size() > 25 ? ", ... (" + items.size() + " total)" : "");
    }

    /** Loaded through the server ResourceManager (datapack path), so no module-encapsulation concerns. */
    public static synchronized JsonObject expectations(MinecraftServer server) {
        if (expectations == null) {
            Resource res = server.getResourceManager().getResource(EXPECTATIONS)
                    .orElseThrow(() -> new GameTestAssertException("missing " + EXPECTATIONS + ": copy tools/refdiff/ref-manifests/de-gametest-expectations.json to DE/src/gametest/resources/data/draconicevolution/gametest/expectations.json"));
            try (BufferedReader reader = res.openAsReader()) {
                expectations = GsonHelper.parse(reader);
            } catch (IOException e) {
                throw new GameTestAssertException("cannot read " + EXPECTATIONS + ": " + e);
            }
            String schema = GsonHelper.getAsString(expectations, "schema", "");
            check("refdiff-gametest-expect/1".equals(schema), () -> "unexpected expectations schema '" + schema + "'");
        }
        return expectations;
    }

    public static void writeJson(String name, JsonElement json) {
        try {
            OUT_DIR.mkdirs();
            Files.writeString(new File(OUT_DIR, name).toPath(), GSON.toJson(json) + "\n", StandardCharsets.UTF_8);
        } catch (IOException e) {
            LOGGER.warn("Could not write {}: {}", name, e.toString());
        }
    }

    /**
     * GameTestServer calls GlobalTestReporter.finish() when all tests are done [V GameTestServer.java:125].
     * Keep the console LogTestReporter and add a JUnit XML file. Only on the gametest server, never on runServer.
     */
    public static synchronized void installReporter() {
        if (reporterInstalled || !ForgeGameTestHooks.isGametestServer()) {
            return;
        }
        reporterInstalled = true;
        OUT_DIR.mkdirs();
        try {
            JUnitLikeTestReporter junit = new JUnitLikeTestReporter(new File(OUT_DIR, "gametest-junit.xml"));
            LogTestReporter log = new LogTestReporter();
            GlobalTestReporter.replaceWith(new TestReporter() {
                @Override
                public void onTestFailed(GameTestInfo info) {
                    log.onTestFailed(info);
                    junit.onTestFailed(info);
                }

                @Override
                public void onTestSuccess(GameTestInfo info) {
                    log.onTestSuccess(info);
                    junit.onTestSuccess(info);
                }

                @Override
                public void finish() {
                    log.finish();
                    junit.finish();
                }
            });
            LOGGER.info("DEPORT-GATE gametest.junit={}", new File(OUT_DIR, "gametest-junit.xml").getAbsolutePath());
        } catch (ParserConfigurationException e) {
            LOGGER.warn("JUnit gametest reporter unavailable: {}", e.toString());
        }
    }

